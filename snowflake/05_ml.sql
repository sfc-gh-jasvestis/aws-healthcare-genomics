-- Run QC failure risk scoring and sample volume forecast over the synthetic snapshot.
-- Predicts P(confirmed failed run in the next 7 days) per sequencer and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.QC_FAIL_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, b.CATEGORY, b.UTILISATION_TIER, b.INSTRUMENT_AGE_YEARS,
       r.PHASING_PCT, r.LOW_Q30_TILE_PCT,
       AVG(r.PHASING_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS PHASING_7D,
       SUM(r.QC_FAIL_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS FAILS_30D,
       IFF(SUM(r.QC_FAIL_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'FAIL', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.SEQUENCER_DAILY r JOIN RAW.SEQUENCERS b ON b.ID = r.ENTITY_ID
-- Reagent lot holds are site-wide, not instrument-driven, so they are excluded from training.
WHERE r.FAILURE_MODE <> 'Reagent lot hold';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.QC_FAIL_TRAIN AS
SELECT CATEGORY, UTILISATION_TIER, INSTRUMENT_AGE_YEARS, PHASING_PCT, LOW_Q30_TILE_PCT, PHASING_7D, FAILS_30D, LABEL
FROM ML.QC_FAIL_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.QC_FAIL_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, UTILISATION_TIER, INSTRUMENT_AGE_YEARS, PHASING_PCT, LOW_Q30_TILE_PCT, PHASING_7D, FAILS_30D, LABEL
FROM ML.QC_FAIL_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.QC_FAIL_MODEL(
  INPUT_DATA => TABLE(ML.QC_FAIL_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.QC_FAIL_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.QC_FAIL_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'UTILISATION_TIER', UTILISATION_TIER, 'INSTRUMENT_AGE_YEARS', INSTRUMENT_AGE_YEARS,
           'PHASING_PCT', PHASING_PCT, 'LOW_Q30_TILE_PCT', LOW_Q30_TILE_PCT,
           'PHASING_7D', PHASING_7D, 'FAILS_30D', FAILS_30D)):probability:FAIL::FLOAT AS P
  FROM ML.QC_FAIL_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'FAIL', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'FAIL', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'FAIL', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'FAIL', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per sequencer (label unknown, so excluded from features).
CREATE TABLE ML.QC_FAIL_SCORES AS
WITH latest AS (
  SELECT * FROM ML.QC_FAIL_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.QC_FAIL_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'UTILISATION_TIER', UTILISATION_TIER, 'INSTRUMENT_AGE_YEARS', INSTRUMENT_AGE_YEARS,
           'PHASING_PCT', PHASING_PCT, 'LOW_Q30_TILE_PCT', LOW_Q30_TILE_PCT,
           'PHASING_7D', PHASING_7D, 'FAILS_30D', FAILS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:FAIL::FLOAT, 4) AS FAIL_PROB_7D,
       CASE WHEN P:probability:FAIL::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:FAIL::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide daily sample volume forecast (14 days), for lab staffing and reagent planning.
CREATE VIEW ML.DAILY_SAMPLES AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(SAMPLE_COUNT)::FLOAT AS SAMPLE_COUNT
FROM RAW.SEQUENCER_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.SAMPLE_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_SAMPLES),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'SAMPLE_COUNT'
);

CREATE TABLE ML.SAMPLE_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS SAMPLE_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.SAMPLE_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
