-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT seq.ID AS ENTITY_ID, seq.NAME AS ENTITY_NAME,
       seq.REGION, seq.CATEGORY, seq.UTILISATION_TIER, seq.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.SAMPLE_COUNT) AS SAMPLE_COUNT,
       SUM(observation.GB_OUTPUT) AS GB_OUTPUT,
       SUM(observation.GB_TARGET) AS GB_TARGET,
       SUM(observation.QC_FLAG_COUNT) AS QC_FLAG_COUNT,
       SUM(observation.QC_FAIL_COUNT) AS QC_FAIL_COUNT,
       SUM(observation.RERUN_COUNT) AS RERUN_COUNT,
       SUM(observation.PM_DUE) AS PM_DUE,
       SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       100.0 * SUM(observation.GB_OUTPUT) / NULLIF(SUM(observation.GB_TARGET), 0) AS YIELD_ATTAINMENT_PCT,
       100.0 * SUM(observation.QC_FAIL_COUNT) / NULLIF(SUM(observation.QC_FLAG_COUNT), 0) AS FLAG_PRECISION_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       AVG(observation.PHASING_PCT) AS AVG_PHASING_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.SEQUENCER_DAILY observation
JOIN RAW.SEQUENCERS seq ON seq.ID = observation.ENTITY_ID
GROUP BY seq.ID, seq.NAME, seq.REGION, seq.CATEGORY, seq.UTILISATION_TIER, seq.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(SAMPLE_COUNT) AS SAMPLE_COUNT, SUM(GB_OUTPUT) AS GB_OUTPUT,
       SUM(GB_TARGET) AS GB_TARGET,
       SUM(QC_FLAG_COUNT) AS QC_FLAG_COUNT, SUM(QC_FAIL_COUNT) AS QC_FAIL_COUNT,
       100.0 * SUM(GB_OUTPUT) / NULLIF(SUM(GB_TARGET), 0) AS YIELD_ATTAINMENT_PCT
FROM RAW.SEQUENCER_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.FAILURE_MODE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT FAILURE_MODE, SUM(QC_FLAG_COUNT) AS QC_FLAG_COUNT,
       SUM(QC_FAIL_COUNT) AS QC_FAIL_COUNT,
       SUM(RERUN_COUNT) AS RERUN_COUNT,
       SUM(GB_OUTPUT) AS FLAGGED_DAY_GB_OUTPUT,
       100.0 * SUM(QC_FAIL_COUNT) / NULLIF(SUM(QC_FLAG_COUNT), 0) AS FLAG_PRECISION_PCT
FROM RAW.SEQUENCER_DAILY
WHERE QC_FLAG_COUNT > 0
GROUP BY FAILURE_MODE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(SAMPLE_COUNT) AS SAMPLES, SUM(GB_OUTPUT) AS GB_OUT,
         SUM(GB_TARGET) AS GB_TGT,
         SUM(QC_FLAG_COUNT) AS FLAGS, SUM(QC_FAIL_COUNT) AS FAILED,
         SUM(RERUN_COUNT) AS RERUNS,
         SUM(PM_DUE) AS PM_DUE, SUM(PM_COMPLETED) AS PM_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.SEQUENCER_DAILY
), fleet AS (SELECT COUNT(*) AS SEQUENCER_COUNT FROM RAW.SEQUENCERS),
kits AS (
  SELECT 100.0 * SUM(LEAST(ON_HAND_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(ON_ORDER_QTY) AS ON_ORDER
  FROM RAW.REAGENT_KITS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Yield Attainment' AS TITLE,
         100.0 * GB_OUT / NULLIF(GB_TGT, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Samples Sequenced', SAMPLES, '' FROM observations
  UNION ALL SELECT 3, 'Data Output (TB)', GB_OUT / 1e3, '' FROM observations
  UNION ALL SELECT 4, 'QC Flags', FLAGS, '' FROM observations
  UNION ALL SELECT 5, 'Confirmed Failed Runs', FAILED, '' FROM observations
  UNION ALL SELECT 6, 'QC Flag Precision', 100.0 * FAILED / NULLIF(FLAGS, 0), '%' FROM observations
  UNION ALL SELECT 7, 'Failed Runs Re-queued', RERUNS, '' FROM observations
  UNION ALL SELECT 8, 'PM Compliance', 100.0 * PM_COMPLETED / NULLIF(PM_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Sequencers Monitored', SEQUENCER_COUNT, '' FROM fleet
  UNION ALL SELECT 10, 'Reagent Kit Coverage', COVERAGE_PCT, '%' FROM kits
  UNION ALL SELECT 11, 'Kits On Order', ON_ORDER, '' FROM kits
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.FAILURE_MODE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
